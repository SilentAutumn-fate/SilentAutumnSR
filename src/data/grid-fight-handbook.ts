/**
 * Categories whose client-side counting walks a config row per id. A single id
 * without a row (or without a monster list) throws inside `_GetCompletedItemCount`
 * and the entrance page renders black, so they default to the Season 1 pools.
 */
const riskyCategories = process.env.SASR_GF_HANDBOOK_RISKY === '1';

export const gridFightHandbook = {
    // Safe: the client skips ids it cannot resolve.
    roles: merge(gridFightProfile.roles, clientExtras.roles),
    equipItems: merge(gridFightProfile.equipment, clientExtras.items),
    augments: merge(gridFightProfile.augments, clientExtras.augments),
    // Safe: these types count `set.Count` directly, no config lookup.
    spotlights: merge([], clientExtras.spotlights),
    affixes: merge(gridFightProfile.affixes, clientExtras.affixes),
    // Risky: one unknown id throws while the handbook page is built.
    portals: riskyCategories
        ? merge(gridFightProfile.portals, clientExtras.portals)
        : merge(gridFightProfile.portals, []),
    petPals: riskyCategories ? merge([], clientExtras.petPals) : [],
    monsters: riskyCategories
        ? merge(gridFightProfile.camps, clientExtras.camps)
        : merge(gridFightProfile.camps, []),
};
