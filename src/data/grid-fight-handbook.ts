// GridFight handbook catalogue.
//
// The client does not render handbook rows by itself: `GridFightHandBookStatus`
// counts "collected" entries by iterating the sets we send and looking every id
// up in its own config tables. That lookup is not uniformly null-safe:
//
//   * roles (type 1)  – unknown ids are skipped (`_CountCompletedHandBookRoles`)
//   * equip  (type 2) – unknown ids are skipped (`_IsHandBookVisibleEquipRow`)
//   * augment(type 3) – unknown ids are skipped
//   * portal (type 4) – a missing config row **throws** (0xDB3A5A2)
//   * monster(type 5) – a missing row **throws** (0xDB3A5B1) and a row whose
//                       sub-list is null throws too (0xDB3A5B6)
//   * spotlight(7)/affix(8) – count is simply `set.Count`
//
// The 2026-11-10 black screen ("UITransition ... GridFightS2EntrancePage,
// error: NullReferenceException at _GetCompletedItemCount") came from the
// type 5 path: camp ids mined from the route table (101/201/301/3051 …) resolve
// to rows without a monster list. So the risky categories only ship the Season 1
// pools that are known to render, and the mined extras are opt-in through
// `SASR_GF_HANDBOOK_RISKY=1` for bisecting.
//
// Mined from StarRail_4.6.51/StarRail_Data/Persistent/DesignData/Windows:
//   augments  Config/Level/GridFight/Augment/<id>.json
//   spotlights Config/Level/GridFight/SpotLight/<id>.json
//   equipment SpriteOutput/GridFight/EquipmentSmall/<id>.png
//   portals   SpriteOutput/GridFight/Portal/<id>.png
//   pet pals  Config/Level/GridFight/petpal/GridFightPetPalEff<id>.json
//   affixes   BuffIcon/Icon_GridFight_Affix_<id>
//   roles     SpriteOutput/AvatarIcon/Avatar/<id>.png
import { gridFightProfile } from './grid-fight-profile';

function merge(base: number[], extra: number[]): number[] {
    return [...new Set([...base, ...extra])].filter((id) => id > 0).sort((a, b) => a - b);
}

