/**
 * SilentAutumnSR protocol codegen.
 *
 * Inputs:
 *   src/proto/StarRail.proto   - protobuf message/enum definitions
 *   src/proto/CmdId.json       - message name -> command id
 *   src/proto/CmdId.extra.json - names the dump leaves obfuscated
 *                                (see dev/tools/reconcile-cmdid.js)
 *
 * Since 4.7 the .proto and CmdId.json are no longer downloaded from
 * https://github.com/yuvlian/hsr-proto: dev/tools/zig2proto.js reconstructs them from
 * pearl-sr's generated Zig (see docs/UPGRADE-4.7.md). The 4.5.54 originals are
 * kept under _probe/sasr-proto-4.5.54 outside the repo.
 *
 * Outputs (generated, git-ignored, regenerate with `node tools/gen-proto.js`):
 *   src/proto/starrail.gen.js  - protobufjs static module ($root.starrail.*)
 *   src/proto/starrail.ts      - runtime wrapper + type mirror of the namespace
 *   src/proto/cmdId.ts         - CmdID lookup table (Cmd-prefixed names)
 *
 * The `.gen.js` suffix matters: starrail.ts is the wrapper module and tsc must
 * not emit a file that collides with it.
 *
 * Why the type mirror is `any`:
 *   pbts silently fails on a module this size, and type-checking a 10 MB .d.ts
 *   costs minutes per build. starrail.ts therefore exposes the real runtime
 *   value plus a namespace of `type X = any` aliases, so call sites keep the
 *   `starrail.PlayerLoginScRsp` spelling (and stay greppable/readable) while
 *   the compiler stays fast. `node tools/selftest.js` covers the field names at
 *   runtime instead.
 *
 * Notes
 *   - The upstream dump declares no `package`, so protobufjs would emit every
 *     symbol flat on the module root. Call sites address them as `starrail.Foo`,
 *     so codegen injects a single `package starrail;` line into a temporary copy
 *     rather than editing the upstream file. Swapping in a new dump therefore
 *     stays a pure file replacement.
 *   - No .d.ts is emitted. `pbts` silently fails on a module this size, and
 *     type-checking a 55 MB generated file costs minutes per build. starrail.ts
 *     instead wraps the runtime and mirrors the namespace with `any` aliases.
 */
const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

const root = path.resolve(__dirname, '..');
const protoDir = path.join(root, 'src', 'proto');
const upstreamProto = path.join(protoDir, 'StarRail.proto');
const cmdIdJson = path.join(protoDir, 'CmdId.json');
const cmdIdExtraJson = path.join(protoDir, 'CmdId.extra.json');
const packagedProto = path.join(protoDir, '.StarRail.packaged.proto');
const outJs = path.join(protoDir, 'starrail.gen.js');
const outWrapper = path.join(protoDir, 'starrail.ts');
const outCmdId = path.join(protoDir, 'cmdId.ts');

const PBJS = path.join(root, 'node_modules', 'protobufjs-cli', 'bin', 'pbjs');

const step = (msg) => console.log(`[gen-proto] ${msg}`);
const die = (msg) => {
    console.error(`[gen-proto] ERROR: ${msg}`);
    process.exit(1);
};

function writePackagedProto() {
    if (!fs.existsSync(upstreamProto)) die(`missing ${upstreamProto}`);
    const source = fs.readFileSync(upstreamProto, 'utf-8');
    if (/^\s*package\s+starrail\s*;/m.test(source)) {
        fs.copyFileSync(upstreamProto, packagedProto);
        return;
    }
    const syntaxLine = /^\s*syntax\s*=\s*"[^"]*"\s*;/m;
    if (!syntaxLine.test(source)) die('could not find a syntax statement in StarRail.proto');
    fs.writeFileSync(
        packagedProto,
        source.replace(syntaxLine, (m) => `${m}\n\npackage starrail;`),
        'utf-8',
    );
}

function generateCmdId() {
    const raw = JSON.parse(fs.readFileSync(cmdIdJson, 'utf-8'));

    /** @type {Record<string, number>} */
    const cmdIds = {};
    for (const [name, value] of Object.entries(raw)) {
        if (typeof value !== 'number') continue;
        cmdIds[name.startsWith('Cmd') ? name : 'Cmd' + name] = value;
    }

    const extraCount = 0; // Command IDs come exclusively from the primary CmdId.json.

    // Deterministic ordering keeps diffs small when hsr-proto updates.
    const sorted = Object.fromEntries(
        Object.keys(cmdIds)
            .sort()
            .map((k) => [k, cmdIds[k]]),
    );

    const out =
        '// AUTO-GENERATED by tools/gen-proto.js - do not edit by hand.\n' +
        '// Source: https://github.com/yuvlian/hsr-proto (CmdId.json)\n' +
        `// Entries: ${Object.keys(sorted).length} (${extraCount} reconciled from CmdId.extra.json)\n` +
        `export const CmdID: { [key: string]: number } = ${JSON.stringify(sorted, null, 4)};\n`;
    fs.writeFileSync(outCmdId, out + `\nObject.assign(CmdID, require('./profile').protocolCommands(CmdID));\n`, 'utf-8');
    step(`wrote cmdId.ts (${Object.keys(sorted).length} entries, ${extraCount} reconciled)`);
}

/**
 * Every top-level message/enum name in the proto, used to mirror the runtime
 * namespace as `any` type aliases.
 */
function collectTypeNames() {
    const names = new Set();
    for (const n of JSON.parse(fs.readFileSync(path.join(protoDir,'4.7.51/handler-type-names.json'),'utf8'))) names.add(n);
    const runtime=JSON.parse(fs.readFileSync(path.join(protoDir,'4.7.51/schema.json'),'utf8'));
    for (const n of Object.keys(runtime.nested)) names.add(n);
    for (const line of fs.readFileSync(upstreamProto, 'utf-8').split(/\r?\n/)) {
        const m = /^(message|enum)\s+([A-Za-z_]\w*)\s*\{/.exec(line);
        if (m) names.add(m[2]);
    }
    return [...names].sort();
}

function generateWrapper(typeNames) {
    const aliases = typeNames.map((n) => `    export type ${n} = any;`).join('\n');

    const out = `/**
 * AUTO-GENERATED by tools/gen-proto.js - do not edit by hand.
 *
 * Runtime entry point for the protobuf types defined in src/proto/StarRail.proto
 * (from https://github.com/yuvlian/hsr-proto), plus a type mirror of the same
 * namespace.
 *
 * \`starrail.gen.js\` is a ~55 MB protobufjs static module. It is excluded from
 * the TypeScript program (see tsconfig.json) because parsing it costs minutes
 * per build, so it is reached through \`require\` here and copied into dist/ by
 * tools/build.js.
 *
 * The namespace below aliases every generated type to \`any\`: call sites keep
 * the familiar \`starrail.PlayerLoginScRsp\` spelling, but field-level type
 * safety is not enforced. \`node tools/selftest.js\` exercises the encode/decode
 * paths at runtime instead.
 */
/* eslint-disable @typescript-eslint/no-var-requires */
const generated = require('./starrail.gen.js');

/** The protobuf root namespace: \`starrail.PlayerLoginScRsp.encode(msg)\`. */
export const starrail: any = require('./profile').protocolNamespace(generated.starrail);

// Type mirror (${typeNames.length} declarations).
// eslint-disable-next-line @typescript-eslint/no-namespace
export namespace starrail {
${aliases}
}

/** Look up a generated message type by protobuf name, e.g. "PlayerLoginScRsp". */
export function lookupType(name: string): any {
    return starrail[name];
}
`;
    fs.writeFileSync(outWrapper, out, 'utf-8');
    step(`wrote starrail.ts (${typeNames.length} type aliases)`);
}

function main() {
    require('./prepare-protocol');
    writePackagedProto();

    const stamp = path.join(protoDir, '.inputs.sha256');
    const changed = !fs.existsSync(stamp) || fs.readFileSync(stamp,'utf8') !== require('./protocol-inputs')();
    if (!process.argv.includes('--skip-pbjs') || !fs.existsSync(outJs) || changed) {
        step('running pbjs');
        const res = spawnSync(
            process.execPath,
            [PBJS, '-t', 'static-module', '-w', 'commonjs', '-o', outJs, packagedProto],
            { cwd: root, stdio: 'inherit' },
        );
        if (res.status !== 0) die(`pbjs failed with exit code ${res.status}`);
    } else {
        step('reusing existing starrail.gen.js');
    }

    generateWrapper(collectTypeNames());
    generateCmdId();

    try {
        fs.unlinkSync(packagedProto);
    } catch {
        /* best effort */
    }

    step(`starrail.gen.js ${(fs.statSync(outJs).size / 1024 / 1024).toFixed(1)} MB`);
    fs.writeFileSync(path.join(protoDir, '.inputs.sha256'), require('./protocol-inputs')());
    step('done');
}

main();
